"""Tool for analyzing git diff size and determining PR vertical splitting requirements."""

import argparse
import re
import subprocess
from pathlib import Path
from typing import Any

from tool_utils import HandledError, run_tool

# Patterns for autogenerated files and lockfiles to exclude from code sizing.
GENERATED_FILE_PATTERNS = (
    r".*\.pb\.go$",
    r".*_pb2\.py$",
    r".*_pb2_grpc\.py$",
    r".*\.pb\.gw\.go$",
    r".*package-lock\.json$",
    r".*pnpm-lock\.yaml$",
    r".*yarn\.lock$",
    r".*Cargo\.lock$",
    r".*MODULE\.bazel\.lock$",
    r".*go\.sum$",
    r".*\.min\.js$",
    r".*\.min\.css$",
)

# Patterns for unit, integration, and E2E test files.
TEST_FILE_PATTERNS = (
    r".*_test\.go$",
    r".*_test\.py$",
    r".*\.spec\.ts$",
    r".*\.test\.ts$",
    r".*_test\.ts$",
    r".*_test\.js$",
    r"^test/.*",
    r".*/test/.*",
    r"^tests/.*",
    r".*/tests/.*",
    r".*/testing/.*",
    r".*/testdouble/.*",
    r".*fixture.*\.(go|py|ts|js)$",
    r".*fake.*\.(go|py|ts|js)$",
    r".*mock.*\.(go|py|ts|js)$",
)

# Patterns for documentation and markdown files.
DOC_FILE_PATTERNS = (
    r".*\.md$",
    r".*\.markdown$",
    r".*\.rst$",
    r"^docs/.*",
    r".*/docs/.*",
)


def classify_file(file_path: str) -> str:
    """Classifies a relative file path into a category.

    Args:
        file_path: Relative POSIX path of the file.

    Returns:
        One of 'generated', 'test', 'doc', or 'prod'.
    """
    normalized_path = file_path.replace("\\", "/").strip()

    for pattern in GENERATED_FILE_PATTERNS:
        if re.match(pattern, normalized_path, re.IGNORECASE):
            return "generated"

    for pattern in DOC_FILE_PATTERNS:
        if re.match(pattern, normalized_path, re.IGNORECASE):
            return "doc"

    for pattern in TEST_FILE_PATTERNS:
        if re.match(pattern, normalized_path, re.IGNORECASE):
            return "test"

    return "prod"


def get_git_numstat(diff_spec: str | None = None) -> list[tuple[int, int, str]]:
    """Runs git diff --numstat to get line additions, deletions, and filenames.

    Args:
        diff_spec: Optional git diff target (e.g. 'origin/main', 'HEAD~1').

    Returns:
        List of tuples: (added_lines, deleted_lines, file_path).
    """
    cmd = ["git", "diff", "--numstat"]
    if diff_spec:
        cmd.append(diff_spec)

    try:
        res = subprocess.run(cmd, capture_output=True, text=True, check=True)
    except subprocess.CalledProcessError as e:
        raise HandledError(
            f"Failed to execute git diff: {e.stderr.strip()}",
            "Verify that you are inside a valid git workspace and base ref exists.",
        ) from e
    except OSError as e:
        raise HandledError(
            f"Git execution failed: {e}",
            "Ensure git CLI is installed and accessible in system PATH.",
        ) from e

    entries: list[tuple[int, int, str]] = []
    for line in res.stdout.splitlines():
        line = line.strip()
        if not line:
            continue
        parts = line.split("\t")
        if len(parts) < 3:
            continue
        added_str, deleted_str, file_path = parts[0], parts[1], parts[2]
        added = int(added_str) if added_str.isdigit() else 0
        deleted = int(deleted_str) if deleted_str.isdigit() else 0
        entries.append((added, deleted, file_path))

    return entries


def get_untracked_files() -> list[str]:
    """Returns a list of untracked files in the working directory."""
    cmd = ["git", "ls-files", "--others", "--exclude-standard"]
    try:
        res = subprocess.run(cmd, capture_output=True, text=True, check=True)
        return [f.strip() for f in res.stdout.splitlines() if f.strip()]
    except (subprocess.CalledProcessError, OSError):
        return []


def count_file_lines(file_path: str) -> int:
    """Counts non-empty lines in a local file."""
    path = Path(file_path)
    if not path.is_file():
        return 0
    try:
        content = path.read_text(encoding="utf-8", errors="replace")
        return len(content.splitlines())
    except OSError:
        return 0


def analyze_diff_size(args: argparse.Namespace) -> dict[str, Any]:
    """Main analysis function evaluating diff size against thresholds."""
    diff_entries = get_git_numstat(args.base_ref)
    untracked_files = get_untracked_files() if args.include_untracked else []

    file_stats: list[dict[str, Any]] = []
    seen_files: set[str] = set()

    for added, deleted, file_path in diff_entries:
        seen_files.add(file_path)
        category = classify_file(file_path)
        total = added + deleted
        file_stats.append(
            {
                "path": file_path,
                "category": category,
                "added": added,
                "deleted": deleted,
                "total": total,
            }
        )

    for untracked in untracked_files:
        if untracked in seen_files:
            continue
        category = classify_file(untracked)
        lines = count_file_lines(untracked)
        file_stats.append(
            {
                "path": untracked,
                "category": category,
                "added": lines,
                "deleted": 0,
                "total": lines,
            }
        )

    prod_lines = sum(f["total"] for f in file_stats if f["category"] == "prod")
    test_lines = sum(f["total"] for f in file_stats if f["category"] == "test")
    doc_lines = sum(f["total"] for f in file_stats if f["category"] == "doc")
    generated_lines = sum(f["total"] for f in file_stats if f["category"] == "generated")
    total_code_lines = prod_lines + test_lines

    exceeded_reasons: list[str] = []
    if prod_lines >= args.prod_threshold:
        exceeded_reasons.append(
            f"Production code diff ({prod_lines} lines) exceeds threshold ({args.prod_threshold} lines)."
        )
    if total_code_lines >= args.total_code_threshold:
        exceeded_reasons.append(
            f"Total code diff (prod + tests = {total_code_lines} lines) exceeds threshold ({args.total_code_threshold} lines)."
        )
    if doc_lines >= args.doc_threshold:
        exceeded_reasons.append(
            f"Documentation/markdown diff ({doc_lines} lines) exceeds threshold ({args.doc_threshold} lines)."
        )

    should_trigger_split = len(exceeded_reasons) > 0

    return {
        "thresholds": {
            "prod_code": args.prod_threshold,
            "total_code": args.total_code_threshold,
            "docs": args.doc_threshold,
        },
        "metrics": {
            "prod_code_lines": prod_lines,
            "test_code_lines": test_lines,
            "total_code_lines": total_code_lines,
            "doc_lines": doc_lines,
            "generated_lines": generated_lines,
        },
        "threshold_exceeded": should_trigger_split,
        "exceeded_reasons": exceeded_reasons,
        "should_trigger_split_verifier": should_trigger_split,
        "files_count": len(file_stats),
        "files": file_stats,
    }


def main() -> None:
    """Main entrypoint for analyze_diff_size tool."""
    parser = argparse.ArgumentParser(
        description="Analyze git diff size against production, total code, and doc thresholds."
    )
    parser.add_argument(
        "--base-ref",
        default=None,
        help="Optional git diff base reference (e.g. 'origin/main', 'HEAD~1'). Default inspects working tree diff.",
    )
    parser.add_argument(
        "--prod-threshold",
        type=int,
        default=400,
        help="Threshold in lines for production code (default: 400).",
    )
    parser.add_argument(
        "--total-code-threshold",
        type=int,
        default=1000,
        help="Threshold in lines for combined production and test code (default: 1000).",
    )
    parser.add_argument(
        "--doc-threshold",
        type=int,
        default=1000,
        help="Threshold in lines for documentation/markdown files (default: 1000).",
    )
    parser.add_argument(
        "--no-untracked",
        dest="include_untracked",
        action="store_false",
        default=True,
        help="Do not include untracked new files in diff analysis.",
    )
    run_tool(parser, analyze_diff_size)


if __name__ == "__main__":
    main()
