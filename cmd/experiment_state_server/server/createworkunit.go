// CreateWorkUnit orchestrates the creation of a new work unit for an experiment.
func (s *Server) CreateWorkUnit(ctx context.Context, req *apipb.CreateWorkUnitRequest) (*lropb.Operation, error) {
	ctx = logging.InjectOperation(ctx, "")
	logging.Info(ctx, "Create work unit", "request", req)

	// 1. Authenticate the user.
	logging.Debug(ctx, "Extracting user identity from context")
	email, _, err := s.auth.AuthenticateUserFromContext(ctx)
	if err != nil {
		return nil, err
	}

	// 2. Validate the request payload.
	xid, err := validator.ValidateExperimentName(req.GetParent())
	if err != nil {
		logging.Warn(ctx, "Failed to validate experiment name", "error", err)
		return nil, fmt.Errorf("failed to validate experiment name: %w (%v)", status.ErrInvalidArgument, err)
	}
	ctx = logging.WithExperimentName(ctx, req.GetParent())
	if err := validator.ValidateCreateWorkUnitRequest(req); err != nil {
		logging.Warn(ctx, "CreateWorkUnit validation failed", "error", err)
		return nil, fmt.Errorf("CreateWorkUnit validation failed: %w", err)
	}

	if req.GetWorkUnitId() == 0 {
		logging.Warn(ctx, "work_unit_id not provided, will be generated by server")
	}

	// 2.1. Check that the work unit is compatible with the execution environment.
	executionEnv, err := s.defaultExecutionEnvironment()
	if err != nil {
		logging.Error(ctx, "Failed to get execution environment", "error", err)
		return nil, err
	}
	if isCompatible, reason := executionEnv.IsCompatibleWithWorkUnit(req.GetWorkUnit()); !isCompatible {
		logging.Warn(ctx, "CreateWorkUnit environment compatibility check failed", "execution_environment", executionEnv.Name(), "reason", reason)
		return nil, fmt.Errorf("CreateWorkUnit environment compatibility check failed for execution environment %q (%s): %w", executionEnv.Name(), reason, status.ErrInvalidArgument)
	}

	// 3. Authorize the caller to create work units for this experiment.
	authorized, err := s.checkUserAuthorization(ctx, validator.ConstructXIDName(xid), email, xidmsgpb.XidAcls_WRITER.Enum())
	if err != nil {
		return nil, err
	}
	if !authorized {
		logging.Warn(ctx, "User not authorized to create work units for XID", "user", email)
		return nil, fmt.Errorf("user %s is not authorized to create work units for XID %d: %w", email, xid, status.ErrPermissionDenied)
	}

	// 4. Assemble the full WorkUnit object from the request.
	wu := validator.FillWorkUnitNullValues(req.GetWorkUnit())

	// 4.1. Construct the work unit name and current work unit execution.
	// If the work unit ID is 0, the storage layer will generate a new ID and update the names.
	wu.Name = validator.ConstructWorkUnitName(xid, req.GetWorkUnitId())
	wu.CurrentWorkUnitExecution = newWorkUnitExecution(xid, req.GetWorkUnitId())

	// 4.2. Inject the execution environment on work unit creation.
	wu, err = executionEnv.InjectOnWorkUnitCreation(ctx, s, wu)
	if err != nil {
		logging.Error(ctx, "Failed to inject execution environment data into work unit", "error", err)
		return nil, fmt.Errorf("failed to inject execution environment data into work unit: %w", err)
	}

	// 5. Persist the new work unit to the storage layer.
	newWorkUnit, err := s.storage.CreateWorkUnit(ctx, wu)
	if err != nil {
		logging.Error(ctx, "Failed to save work unit", "error", err)

		// The storage layer's Create() method uses atomic "create if not exists",
		// so an AlreadyExists error means the client sent a duplicate ID.
		if status.ExtractCanonicalCode(err) == status.AlreadyExists {
			// If the storage layer returns AlreadyExists, newWorkUnit contains the conflicting work unit.
			return nil, fmt.Errorf("work unit %s already exists: %w", newWorkUnit.GetName(), status.ErrAlreadyExists)
		}
		return nil, fmt.Errorf("failed to save work unit: %v: %w", err, status.ErrInternal)
	}

	// 5.1. Fetch the name of the newly created work unit.
	ctx = logging.WithWorkUnitExecutionName(ctx, newWorkUnit.GetCurrentWorkUnitExecution().GetName())
	_, wid, err := validator.ValidateWorkUnitName(newWorkUnit.GetName())
	if err != nil {
		logging.Error(ctx, "Failed to validate work unit name", "error", err)
		return nil, fmt.Errorf("failed to validate work unit name: %w (%v)", status.ErrInternal, err)
	}

	// 6. Create a long-running operation for the work unit creation.
	metadata := &msgpb.OperationMetadata{
		Target:            newWorkUnit.GetName(),
		ActionType:        msgpb.OperationMetadata_CREATE,
		OriginalRequester: email,
	}
	operation, err := s.storage.AddWorkUnitOperation(ctx, xid, wid, metadata)
	if err != nil {
		logging.Error(ctx, "Failed to add work unit operation", "error", err)
		return nil, fmt.Errorf("failed to add work unit operation: %w (%v)", status.ErrInternal, err)
	}

	// 6.1. Ensure that the operation is marked as done if an error is returned from now on.
	defer func() {
		s.stopOperationOnError(ctx, operation, err)
	}()

	// 7. Create the action to enqueue the work unit for scheduling.
	logging.Debug(ctx, "Enqueuing work unit for scheduling")

	// 8. Fetch the experiment to get the priority for the work unit creation.
	exp, err := s.storage.FetchExperiment(ctx, xid)
	if err != nil {
		logging.Error(ctx, "Failed to fetch experiment", "error", err)
		return nil, fmt.Errorf("failed to fetch experiment: %w (%v)", status.ErrInternal, err)
	}

	// 9. Enqueue or Buffer the work unit for scheduling.
	action := client.CreateAction(exp.GetPriority(), email)
	if s.localPaused.Load() {
		logging.Info(ctx, "Scheduling is globally paused. Buffering task in Spanner.", "work_unit", newWorkUnit.GetName())
		traceID, _ := logging.OperationID(ctx)
		task := &storage.PausedTask{
			BitReversedXid: reverseBits(xid),
			WorkUnitID:     wid,
			TaskID:         newWorkUnit.GetCurrentWorkUnitExecution().GetName(),
			Target:         newWorkUnit.GetCurrentWorkUnitExecution().GetName(),
			Action:         action,
			OperationName:  operation.GetName(),
			TraceID:        traceID,
		}

		err = s.storage.BufferPausedTask(ctx, task, nil)
		if err != nil {
			logging.Error(ctx, "Failed to buffer paused task in Spanner", "error", err)
			return nil, fmt.Errorf("failed to buffer paused task: %w", err)
		}
	} else {
		err = s.taskQueueClient.EnqueueWorkUnitTask(ctx, newWorkUnit.GetCurrentWorkUnitExecution().GetName(), newWorkUnit, action, operation.GetName())
		if err != nil {
			log.ErrorContextf(ctx, "Failed to enqueue work unit for scheduling %s: %v", newWorkUnit.GetName(), err)
			enqueueErr := err
			_, _, eid, err := validator.ValidateWorkUnitExecutionName(newWorkUnit.GetCurrentWorkUnitExecution().GetName())
			if err != nil {
				log.ErrorContextf(ctx, "Failed to validate work unit execution name: %v", err)
				return nil, fmt.Errorf("failed to validate work unit execution name: %w (%v)", status.ErrInternal, err)
			}

			if statusMsgErr := s.updateWorkUnitExecutionStatusMessage(ctx, xid, wid, eid, &msgpb.StructuredMessage{
				UserFacingText: "Work unit was created but could not be scheduled for execution. Please restart the work unit.",
				Severity:       msgpb.StructuredMessage_FATAL,
				Source:         msgpb.StructuredMessage_XMANAGER_BACKEND,
			}, false); statusMsgErr != nil {
				logging.Error(ctx, "Failed to update work unit execution status message after failed create attempt", "error", statusMsgErr)
			}
			logging.Error(ctx, "Failed to enqueue work unit for scheduling", "error", enqueueErr)
			return nil, fmt.Errorf("failed to enqueue work unit for scheduling: %w (%v)", status.ErrInternal, enqueueErr)
		}
	}


	// 10. Return the successful response.
	logging.Info(ctx, "Created work unit", "work_unit", newWorkUnit.GetName())
	return operation, nil
}
