// CreateWorkUnit orchestrates the creation of a new work unit for an experiment.
func (h *WorkUnitHandler) CreateWorkUnit(ctx context.Context, req *msgpb.CreateWorkUnitRequest) (*lropb.Operation, error) {
	ctx = logging.InjectOperation(ctx, "")
	logging.Info(ctx, "Create work unit", "request", req)

	// 1. Authenticate the user.
	logging.Debug(ctx, "Extracting user identity from context")
	email, _, err := h.auth.AuthenticateUserFromContext(ctx)
	if err != nil {
		return nil, err
	}

	// 2. Validate the parent experiment name and enrich logging context.
	xid, err := validator.ValidateExperimentName(req.GetParent())
	if err != nil {
		logging.Warn(ctx, "Failed to validate experiment name", "error", err)
		return nil, fmt.Errorf("failed to validate experiment name: %w (%v)", grpcerr.ErrInvalidArgument, err)
	}
	ctx = logging.WithExperimentName(ctx, req.GetParent())

	// 3. Authorize the caller to create work units for this experiment.
	if err := h.authorizeCreateWorkUnit(ctx, xid, email); err != nil {
		return nil, err
	}

	// 4. Validate the request payload.
	if err := validator.ValidateCreateWorkUnitRequest(req); err != nil {
		logging.Warn(ctx, "CreateWorkUnit validation failed", "error", err)
		return nil, fmt.Errorf("CreateWorkUnit validation failed: %w", err)
	}

	if req.GetWorkUnitId() == 0 {
		logging.Warn(ctx, "work_unit_id not provided, will be generated by server")
	}

	executionEnv, err := h.checkExecutionEnvCompatibility(ctx, req.GetWorkUnit())
	if err != nil {
		return nil, err
	}

	// 5. Assemble the full WorkUnit object from the request.
	wu := validator.FillWorkUnitNullValues(req.GetWorkUnit())

	// 4.1. Construct the work unit name and current work unit execution.
	// If the work unit ID is 0, the storage layer will generate a new ID and update the names.
	wu.Name = validator.ConstructWorkUnitName(xid, req.GetWorkUnitId())
	wu.CurrentWorkUnitExecution = newWorkUnitExecution(xid, req.GetWorkUnitId())

	// 4.2. Inject the execution environment on work unit creation.
	wu, err = executionEnv.InjectOnWorkUnitCreation(ctx, h.server, wu)
	if err != nil {
		logging.Error(ctx, "Failed to inject execution environment data into work unit", "error", err)
		return nil, fmt.Errorf("failed to inject execution environment data into work unit: %w", err)
	}

	// 5. Persist the new work unit to the storage layer.
	newWorkUnit, err := workunit.CreateWorkUnit(ctx, h.storage, wu)
	if err != nil {
		logging.Error(ctx, "Failed to save work unit", "error", err)

		// TODO(b/517479143): Fix nil pointer dereference: newWorkUnit is nil when storage returns error, so newWorkUnit.GetName() panics.
		if status.Code(err) == codes.AlreadyExists {
			// If the storage layer returns AlreadyExists, newWorkUnit contains the conflicting work unit.
			return nil, fmt.Errorf("work unit %s already exists: %w", wu.GetName(), grpcerr.ErrAlreadyExists)
		}
		return nil, fmt.Errorf("failed to save work unit: %v: %w", err, grpcerr.ErrInternal)
	}

	// 5.1. Fetch the name of the newly created work unit.
	ctx = logging.WithWorkUnitExecutionName(ctx, newWorkUnit.GetCurrentWorkUnitExecution().GetName())
	_, wid, err := validator.ValidateWorkUnitName(newWorkUnit.GetName())
	if err != nil {
		logging.Error(ctx, "Failed to validate work unit name", "error", err)
		return nil, fmt.Errorf("failed to validate work unit name: %w (%v)", grpcerr.ErrInternal, err)
	}

	// 6. Create a long-running operation for the work unit creation.
	metadata := &msgpb.OperationMetadata{
		Target:            newWorkUnit.GetName(),
		ActionType:        msgpb.OperationMetadata_CREATE,
		OriginalRequester: email,
	}
	operation, err := h.storage.AddWorkUnitOperation(ctx, xid, wid, metadata)
	if err != nil {
		logging.Error(ctx, "Failed to add work unit operation", "error", err)
		return nil, fmt.Errorf("failed to add work unit operation: %w (%v)", grpcerr.ErrInternal, err)
	}

	// 6.1. Ensure that the operation is marked as done if an error is returned from now on.
	defer func() {
		h.stopOperationOnError(ctx, operation, err)
	}()

	// 7. Enqueue the work unit for scheduling.
	logging.Debug(ctx, "Enqueuing work unit for scheduling")
	if err = h.enqueueWorkUnitOnCreation(ctx, xid, wid, newWorkUnit, email, operation); err != nil {
		return nil, err
	}

	// 8. Return the successful response.
	logging.Info(ctx, "Created work unit", "work_unit", newWorkUnit.GetName())
	return operation, nil
}

func (h *WorkUnitHandler) enqueueWorkUnitOnCreation(ctx context.Context, xid, wid int64, newWorkUnit *msgpb.WorkUnit, email string, operation *lropb.Operation) error {
	if newWorkUnit == nil || newWorkUnit.GetCurrentWorkUnitExecution() == nil {
		return fmt.Errorf("invalid work unit: %w", grpcerr.ErrInternal)
	}
	if operation == nil {
		return fmt.Errorf("invalid operation: %w", grpcerr.ErrInternal)
	}

	exp, err := h.storage.FetchExperiment(ctx, xid)
	if err != nil {
		logging.Error(ctx, "Failed to fetch experiment", "error", err)
		return fmt.Errorf("failed to fetch experiment: %w (%v)", grpcerr.ErrInternal, err)
	}
	if exp == nil {
		return fmt.Errorf("failed to fetch experiment: experiment %d not found: %w", xid, grpcerr.ErrInternal)
	}

	notifyWhen := h.requiredNotifyWhen(ctx, xid, wid)
	err = h.actuator.EnqueueWorkUnitTask(ctx, newWorkUnit.GetCurrentWorkUnitExecution().GetName(), newWorkUnit, client.CreateAction(exp.GetPriority(), email, notifyWhen), operation.GetName())
	if err != nil {
		logging.Error(ctx, "Failed to enqueue work unit for scheduling", "name", newWorkUnit.GetName(), "error", err)
		enqueueErr := err
		_, _, eid, err := validator.ValidateWorkUnitExecutionName(newWorkUnit.GetCurrentWorkUnitExecution().GetName())
		if err != nil {
			logging.Error(ctx, "Failed to validate work unit execution name", "error", err)
			return fmt.Errorf("failed to validate work unit execution name: %w (%v)", grpcerr.ErrInternal, err)
		}

		if statusMsgErr := h.updateWorkUnitExecutionStatusMessage(ctx, xid, wid, eid, &msgpb.StructuredMessage{
			UserFacingText: "Work unit was created but could not be scheduled for execution. Please restart the work unit.",
			Severity:       msgpb.StructuredMessage_FATAL,
			Source:         msgpb.StructuredMessage_XMANAGER_BACKEND,
		}, false); statusMsgErr != nil {
			logging.Error(ctx, "Failed to update work unit execution status message after failed create attempt", "error", statusMsgErr)
		}
		logging.Error(ctx, "Failed to enqueue work unit for scheduling", "error", enqueueErr)
		return fmt.Errorf("failed to enqueue work unit for scheduling: %w (%v)", grpcerr.ErrInternal, enqueueErr)
	}
	return nil
}

func (h *WorkUnitHandler) checkExecutionEnvCompatibility(ctx context.Context, wu *msgpb.WorkUnit) (ee.Environment, error) {
	executionEnv, err := h.defaultExecutionEnvironment()
	if err != nil {
		logging.Error(ctx, "Failed to get execution environment", "error", err)
		return nil, err
	}
	if isCompatible, reason := executionEnv.IsCompatibleWithWorkUnit(wu); !isCompatible {
		logging.Warn(ctx, "CreateWorkUnit environment compatibility check failed", "execution_environment", executionEnv.Name(), "reason", reason)
		return nil, fmt.Errorf("CreateWorkUnit environment compatibility check failed for execution environment %q (%s): %w", executionEnv.Name(), reason, grpcerr.ErrInvalidArgument)
	}
	return executionEnv, nil
}

func (h *WorkUnitHandler) authorizeCreateWorkUnit(ctx context.Context, xid int64, email string) error {
	authorized, err := h.checkUserAuthorization(ctx, validator.ConstructXIDName(xid), email, xidmsgpb.XidAcls_WRITER.Enum())
	if err != nil {
		return err
	}
	if !authorized {
		logging.Warn(ctx, "User not authorized to create work units for XID", "user", email)
		return fmt.Errorf("user %s is not authorized to create work units for XID %d: %w", email, xid, grpcerr.ErrPermissionDenied)
	}
	return nil
}
