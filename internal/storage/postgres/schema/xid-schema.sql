-- Canonical PostgreSQL XID schema, mirroring internal/storage/spanner/schema/xid-schema.sql.

-- Table that holds the XIDs.
CREATE TABLE Xids (
  Xid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Creator TEXT NOT NULL,
  OriginatingSystem BYTEA NOT NULL, -- cloud.xmanager.v1.OriginatingSystem
  -- Populated on write from OriginatingSystem.endpoint for searching without parsing the proto.
  Endpoint TEXT NOT NULL,
  Acls BYTEA NOT NULL, -- cloud.xmanager.v1.XidAcls
  ParentXid BIGINT NOT NULL DEFAULT 0,
  CreateTime TIMESTAMPTZ NOT NULL,
  UpdateTime TIMESTAMPTZ NOT NULL
);

CREATE INDEX XidsByCreator ON Xids (Creator);
