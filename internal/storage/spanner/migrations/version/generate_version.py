"""Helper script to generate Go schema version constants from SQL files."""

import os
import sys


def main():
    if len(sys.argv) < 3:
        print("Usage: generate_version.py <var_name> <out_file> [migration_files...]")
        sys.exit(1)

    var_name = sys.argv[1]
    out_file = sys.argv[2]
    migration_files = sys.argv[3:]

    max_version = 0
    for f in migration_files:
        basename = os.path.basename(f)
        parts = basename.split("_")
        if parts and parts[0].isdigit():
            v = int(parts[0])
            if v > max_version:
                max_version = v

    if max_version == 0:
        print("Error: No migration files found or failed to parse version.", file=sys.stderr)
        sys.exit(1)

    content = f"""// Code generated by Bazel. DO NOT EDIT.
package version

func init() {{
	{var_name} = {max_version}
}}
"""
    with open(out_file, "w", encoding="utf-8") as out:
        out.write(content)


if __name__ == "__main__":
    main()
