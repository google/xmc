CREATE PROTO BUNDLE (
  cloud.xmanager.v1.OriginatingSystem,
  cloud.xmanager.v1.XidAcls
);

CREATE TABLE Xids (
  BitReversedXid INT64 GENERATED BY DEFAULT AS IDENTITY (BIT_REVERSED_POSITIVE),
  Xid INT64 NOT NULL AS (BIT_REVERSE(BitReversedXid, FALSE)) STORED,
  Creator STRING(MAX) NOT NULL,
  OriginatingSystem cloud.xmanager.v1.OriginatingSystem NOT NULL,
  Endpoint STRING(MAX) NOT NULL AS (OriginatingSystem.endpoint) STORED,
  Acls cloud.xmanager.v1.XidAcls NOT NULL,
  ParentXid INT64 NOT NULL DEFAULT (0),
  CreateTime TIMESTAMP NOT NULL OPTIONS (allow_commit_timestamp = TRUE),
  UpdateTime TIMESTAMP NOT NULL OPTIONS (allow_commit_timestamp = TRUE),
) PRIMARY KEY (BitReversedXid);

CREATE INDEX XidsByCreator ON Xids (Creator);
